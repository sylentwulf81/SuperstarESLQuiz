export interface QuestionBank {
  id: string;
  name: string;
  lessonGoal: string;
  questions: Question[];
}

type PromptRow = [prompt: string, answer: string];

function toQuestions(rows: PromptRow[]): OpenTriviaQuestion[] {
  return rows.map(([title, answer], index) => ({
    id: index + 1,
    blockNumber: index + 1,
    type: 'open_trivia',
    title,
    answer,
    rewardCoins: 0,
    category: 'grammar',
  }));
}

